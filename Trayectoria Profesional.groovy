/****************************/  Proyecto Relevante /****************************/ 

Uno de los proyectos más relevantes fue la estandarización de una base de datos que consolidaba información proveniente de múltiples fuentes. 
El principal reto consistía en normalizar estructuras relacionadas con socios que contaban con seguros activos, ya que cada área 
manejaba formatos de informacion distintos.

Diseñé procesos de transformación y validación en PL/SQL para unificar reglas de negocio, controlar calidad de datos y asegurar consistencia 
transaccional. El sistema clasificaba eventos como accidentes laborales, domésticos, agresiones o enfermedades, y representaba visualmente 
lesiones en un modelo anatómico, lo que exigía precisión en el modelado y categorización de información.

El resultado fue una base de datos centralizada, confiable y optimizada, que redujo inconsistencias y permitió análisis más precisos para la 
toma de decisiones entre áreas.

